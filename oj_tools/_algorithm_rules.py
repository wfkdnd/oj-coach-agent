def match_algorithms(problem_text: str) -> list[str]:
    """根据题目文本匹配算法名称列表。"""
    lowered = problem_text.lower()
    found = []
    for rule in ALGORITHM_RULES:
        if any(kw.lower() in lowered for kw in rule["keywords"]):
            found.append(rule["name"])
    return found if found else ["待进一步判断"]
